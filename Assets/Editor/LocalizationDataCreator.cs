    private static void CreateAsset(string fileName, string langName, List<LocalizationEntry> entries)
    {
        const string folder = "Assets/Resources/Localization";

        if (!AssetDatabase.IsValidFolder("Assets/Resources"))
            AssetDatabase.CreateFolder("Assets", "Resources");
        if (!AssetDatabase.IsValidFolder(folder))
            AssetDatabase.CreateFolder("Assets/Resources", "Localization");

        string path = $"{folder}/{fileName}.asset";
        var existing = AssetDatabase.LoadAssetAtPath<LocalizationData>(path);

        if (existing == null)
        {
            existing = ScriptableObject.CreateInstance<LocalizationData>();
            AssetDatabase.CreateAsset(existing, path);
        }

        existing.languageName = langName;
        existing.SetEntries(entries);
        EditorUtility.SetDirty(existing);
    }
